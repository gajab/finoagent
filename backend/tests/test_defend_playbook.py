"""The Defend PLAYBOOK — leg anatomy, the print off straddles, the assignment ladder, waiting, the three goals — and how the
desk uses them on the canonical trap: AAOI's 80/70 put spread opened for $0.34, the stock at ~$68.5 eight days out, earnings
the week after expiry.

Books are generated by Black-Scholes so every expectation is exact; the end-to-end case runs the REAL phase-1/phase-2 handlers
on the pinned spread world with a two-sided market."""
import math

import pytest

from app.services import defend_playbook_service as pb
from app.services import trade_repair_service as tr
from app.services.stock_service import bs_price

R = 0.045


def book(S, dte, vol, strikes=range(40, 125, 5), half=0.03, fwd=None):
    """A two-sided BS book. `fwd` = the price the quotes are struck off (a chain that lags the tape)."""
    px = fwd or S
    out = {}
    for k in strikes:
        for rt, kind in (("P", "put"), ("C", "call")):
            v = vol(k) if callable(vol) else vol
            mid = max(bs_price(px, float(k), dte / 365, R, v, kind), 0.05)
            h = max(0.025, half * mid)
            out.setdefault(float(k), {})[rt] = {"mid": mid, "iv": v, "bid": max(0.01, mid - h), "ask": mid + h}
    return out


def held_spread(bk, short=80.0, long=70.0, entry=(2.60, 2.26), right="P"):
    return {"legs": [{"right": right, "strike": short, "sign": -1, "qty": 1, "entry": entry[0], "mark": bk[short][right]["mid"], "expiry": "2026-10-30"},
                     {"right": right, "strike": long, "sign": 1, "qty": 1, "entry": entry[1], "mark": bk[long][right]["mid"], "expiry": "2026-10-30"}],
            "collected": round((entry[0] - entry[1]) * 100), "stock": None}


