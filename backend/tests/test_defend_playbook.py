# ── the ladder ────────────────────────────────────────────────────────────────────────────────────────────────────
def _ladder(S=68.5):
    near = book(S, 8, 1.0)
    unwind = near[80.0]["P"]["mid"] - near[70.0]["P"]["mid"]
    nat = near[80.0]["P"]["ask"] - near[70.0]["P"]["bid"]
    books = [("2026-11-20", 29, book(S, 29, 1.1)), ("2027-01-15", 85, book(S, 85, 0.95)), ("2028-01-21", 456, book(S, 456, 0.85))]
    lad = pb.assignment_ladder(right="P", short_strike=80, long_strike=70, qty=1, credit_ps=0.34, unwind_ps=unwind,
                               unwind_nat_ps=nat, books=books, spot=S, r=R, earn_days=14)
    return lad, books, unwind


def test_ladder_csp_is_the_lowest_strike_that_pays_for_the_close():
    lad, books, unwind = _ladder()
    for rg, (_e, _d, bk) in zip(lad["rungs"], books):
        c = rg["csp"]
        K = c["strike"]
        assert bk[K]["P"]["mid"] >= unwind - 1e-9                          # pays for the close …
        lower = [k for k in bk if k < K]
        assert all(bk[k]["P"]["mid"] < unwind for k in lower)              # … and nothing lower does
        assert K <= 80
        net = bk[K]["P"]["mid"] - unwind
        assert c["basis"] == pytest.approx(K - 0.34 - net, abs=0.01)       # every credit lowers the price you'd pay
        assert c["net_cash"] >= 0
    bases = [rg["csp"]["basis"] for rg in lad["rungs"]]
    assert bases == sorted(bases, reverse=True)                            # time buys a lower assignment price


def test_ladder_spread_route_pays_for_itself_within_the_width_cap():
    lad, books, unwind = _ladder()
    for rg, (_e, _d, bk) in zip(lad["rungs"], books):
        sp = rg["spread"]
        if not sp:
            continue
        assert 10 <= sp["width"] <= 15 and sp["short"] <= 80
        assert sp["net_cash"] >= 0
        tot = 0.34 + sp["net_cash"] / 100
        assert sp["max_loss"] == pytest.approx(-(sp["width"] - tot) * 100, abs=1.5)
        same = rg["same_width"]
        assert same["net_cash"] == round((bk[80.0]["P"]["mid"] - bk[70.0]["P"]["mid"] - unwind) * 100)
        assert same["net_cash"] < 0                                        # rolling the ITM spread as-is is a DEBIT


