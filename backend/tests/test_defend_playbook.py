def test_the_pick_needs_clearly_better_odds_without_giving_up_expected_value():
    """Within the rule a move replaces holding only with ≥3 points better odds AND an E[P&L] no more than max($15, 2% of the
    close) worse — otherwise it is shown, the verdict names it, and Hold stays the pick."""
    def menu_with(p_beat, ev):
        hold = {"name": "Hold as-is (do nothing)", "category": "hold", "max_loss": -966, "max_gain": 34, "net_cash": 0}
        close = {"name": "Close the trade", "category": "exit", "ev": -760, "net_cash": -790}
        c = {"kind": "overlay", "title": "Add: sell the Oct 30 $81/88 call spread", "orders": ["Sell to open 1× $81 call"], "cash": 40,
             "cash_fill": 30, "cash_natural": 20, "worst": -936, "best": 64, "ev": ev, "p_beat": p_beat, "p_profit": 10, "days": 8,
             "spans_earnings": False, "capital": 700, "note": "n", "added_risk": 0, "wait": None}
        return {"alternatives": [hold, close], "dte_days": 8, "held": {"legs": [{"expiry": "2026-10-30"}], "collected": 34},
                "risk_budget": {"rule_worst": -966, "close_fill": -800, "close_mid": -760, "need": 40, "searched": 10, "allowance": 150,
                                "hold": {"worst": -966, "best": 34, "ev": -740, "p_beat": 31, "p_profit": 16},
                                "best": [c], "more_time": [], "same_strikes": None}}
    pick = lambda m: next(r for r in pb.action_plan(m)["rows"] if r["is_pick"])["title"]
    assert pick(menu_with(33, -740)) == "Hold to Oct 30"                     # +2 points: noise
    assert pick(menu_with(36, -748)) == "Add: sell the Oct 30 $81/88 call spread"
    assert pick(menu_with(40, -800)) == "Hold to Oct 30"                     # better odds bought with $60 of expected value
    assert "nothing clearly beats holding" in pb.action_plan(menu_with(40, -800))["verdict"]


