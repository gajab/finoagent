def _search_world():
    S = 68.5
    near = book(S, 8, 1.0)
    later = [("2026-11-06", 15, book(S, 15, 1.25)), ("2026-11-20", 29, book(S, 29, 1.1)), ("2026-12-18", 57, book(S, 57, 1.0))]
    held = held_spread(near)
    an = pb.position_anatomy(held=held, spot=S, dte=8, r=R, book=near)
    return pb.risk_budget_search(held=held, anatomy=an, near_book=near, near_exp="2026-10-30", near_dte=8, later=later, spot=S, r=R,
                                 vol_of=pb.vol_curve({8: 1.0, 15: 1.25, 29: 1.1, 57: 1.0}), earn_days=14, ticker="AAOI")


def test_every_strategy_family_is_priced_and_labelled_honestly():
    rb = _search_world()
    ex = {x["kind"]: x for x in rb["explorer"]}
    for kind in ("lock", "overlay", "naked", "jade", "fly", "bwb", "bull", "backspread", "calendar", "diagonal", "roll", "restrike", "collar_now"):
        assert kind in ex, kind
    assert ex["naked"]["status"] == "unlimited" and ex["naked"]["best"]["worst"] is None        # a naked call: open-ended
    assert ex["collar_now"]["status"] == "unlimited"                                         # the call sold before the shares arrive
    assert ex["jade"]["status"] == "more" and ex["jade"]["best"]["added_risk"] > 2000         # selling the long back = a naked put
    for x in rb["explorer"]:
        b = x["best"]
        if x["status"] == "rule":
            assert b["worst"] >= rb["rule_worst"] - 5
        if x["status"] == "more":
            assert b["worst"] < rb["rule_worst"] - 5 and b["added_risk"] == rb["rule_worst"] - b["worst"]
        assert x["why"] and x["tested"] >= 1


def test_the_lock_is_a_near_box_inside_your_rule():
    rb = _search_world()
    lock = next(x for x in rb["explorer"] if x["kind"] == "lock")
    b = lock["best"]
    assert lock["status"] == "rule" and b["worst"] >= rb["rule_worst"] - 5
    assert b["best"] - b["worst"] <= 1000                                   # the result is pinned to a narrow band
    k1 = float(b["title"].split("$")[1].split("/")[0])
    assert k1 < 80                                                           # the call spread sits INSIDE the put spread


def test_a_lock_pick_states_the_band_and_what_it_gives_up():
    hold = {"name": "Hold as-is (do nothing)", "category": "hold", "max_loss": -966, "max_gain": 34, "net_cash": 0}
    close = {"name": "Close the trade", "category": "exit", "ev": -760, "net_cash": -790}
    c = {"kind": "lock", "title": "Lock it: sell the Oct 30 $70/78 call spread", "orders": ["Sell to open 1× $70 call Oct 30 @ 3.40"],
         "cash": 218, "cash_fill": 209, "cash_natural": 200, "worst": -757, "best": -557, "ev": -725, "p_beat": 100, "p_profit": 0,
         "days": 8, "spans_earnings": False, "capital": 800, "note": "n", "added_risk": 0, "wait": None,
         "at_spot": -757, "worst_side": "both", "meta": {"k1": 70, "k2": 78}}
    menu = {"ticker": "AAOI", "alternatives": [hold, close], "dte_days": 8, "held": {"legs": [{"expiry": "2026-10-30"}], "collected": 34},
            "risk_budget": {"rule_worst": -966, "close_fill": -844, "close_mid": -801, "need": 42, "searched": 900, "allowance": 150,
                            "hold": {"worst": -966, "best": 34, "ev": -739, "p_beat": 31, "p_profit": 16},
                            "best": [c], "more_time": [], "same_strikes": None, "explorer": []}}
    ap = pb.action_plan(menu)
    assert next(r for r in ap["rows"] if r["is_pick"])["title"] == c["title"]
    assert "about −$757 if AAOI stays where it is" in ap["verdict"] and "−$557 at best" in ap["verdict"]
    assert "−$844" in ap["verdict"] and "16% chance" in ap["verdict"]
    c2 = dict(c, worst=-966, best=-716, at_spot=-716, worst_side="up", meta={"k1": 70, "k2": 82.5})
    menu["risk_budget"]["best"] = [c2]
    v2 = pb.action_plan(menu)["verdict"]
    assert "−$966 at worst — and that only if AAOI rallies past $82.50" in v2     # where the bad outcome lives, said plainly
