def test_waiting_to_roll_an_itm_spread_costs_money_and_iv_rises_while_premium_falls():
    S = 68.5
    near = book(S, 8, 1.0)
    ev = 0.15 ** 2
    post_vol = math.sqrt((1.0 ** 2 * 29 / 365 + ev) / (29 / 365))
    new_mid = bs_price(S, 70, 29 / 365, R, post_vol, "put")
    held = [{"right": "P", "strike": 80, "sign": -1, "qty": 1, "iv": 1.0, "mark": near[80.0]["P"]["mid"]},
            {"right": "P", "strike": 70, "sign": 1, "qty": 1, "iv": 1.0, "mark": near[70.0]["P"]["mid"]}]
    w = pb.wait_cost(held_legs=held, new_legs=[{"right": "P", "strike": 70, "sign": -1, "qty": 1, "dte": 29, "iv": post_vol, "mid": new_mid}],
                     spot=S, r=R, dte_now=8, event_var=ev, earn_days=14, near_vol=1.0)
    assert w["cost_flat"] < -100
    ns = w["new_short"]
    assert ns["iv_later_pct"] > ns["iv_now_pct"] and ns["premium_later"] < ns["premium_now"]


