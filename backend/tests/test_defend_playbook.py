def test_early_assignment_levels():
    S = 68.5
    bk = book(S, 8, 1.0)
    # (a) bid below intrinsic → a holder can't sell it for more than exercising pays
    bk[80.0]["P"]["bid"] = (80 - S) - 0.05
    an = pb.position_anatomy(held=held_spread(bk), spot=S, dte=8, r=R, book=bk)
