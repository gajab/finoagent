def test_event_move_comes_from_the_tight_pair_of_straddles():
    ev = 0.15 ** 2
    base = 1.0
    post_vol = math.sqrt((base ** 2 * 15 / 365 + ev) / (15 / 365))
    far_vol = math.sqrt((0.80 ** 2 * 57 / 365 + ev) / (57 / 365))           # the base vol term-structure falls further out
    books = [("2026-10-30", 8, book(68.5, 8, base)), ("2026-11-06", 15, book(68.5, 15, post_vol)), ("2026-12-18", 57, book(68.5, 57, far_vol))]
    ts = pb.term_structure(books, 68.5, R, earn_days=14)
    assert ts["pre"] == "2026-10-30" and ts["post"] == "2026-11-06"
    assert ts["event_move_pct"] == pytest.approx(15.0, abs=0.4)
    # the far month would have hidden it (its base vol is lower) — the old near/far read
    far_only = tr.implied_event_move(base, far_vol, 8, 57, 14)
    assert far_only is None or far_only < 8.0


