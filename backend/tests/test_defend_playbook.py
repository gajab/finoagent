# ── the pick ──────────────────────────────────────────────────────────────────────────────────────────────────────
def test_a_rejected_fix_falls_back_to_the_better_benchmark():
    """A no-new-money roll that RAISES the worst case is not income-viable, so it must beat the benchmark by
    NONVIABLE_MARGIN. When it doesn't, the pick is the HIGHER-scoring benchmark — AAOI live: wider roll 62, Hold 60,
    Close 57 used to land on Close."""
    import copy
    base = tr.repair_alternatives(legs=[{"strike": 80, "right": "P", "sign": -1, "qty": 1, "entry": 2.60},
                                        {"strike": 70, "right": "P", "sign": 1, "qty": 1, "entry": 2.26}],
                                  spot=68.5, dte_days=8, atm_iv=1.0)
    base["recoverability"].update({"posture": "tested", "p_touch": 99.0, "vrp_pct": -7.0, "trend_pct": -50.0})
    hold0 = next(a for a in base["alternatives"] if a["category"] == "hold")
    found = False
    for d_pop in range(0, 40):
        for fit in (50, 60, 70, 80):
            m = copy.deepcopy(base)
            row = {"name": "Roll to a wider $75/60 put spread", "category": "roll", "group": "adjust", "net_cash": 40.0,
                   "defined_risk": True, "max_loss": round(hold0["max_loss"] * 1.4), "max_gain": 74.0, "ev": hold0["ev"],
                   "pop_pct": (hold0["pop_pct"] or 0) + d_pop, "d_pop": d_pop, "d_ev": 0, "breakevens": [73.9],
                   "legs": [{"action": "SELL", "right": "P", "strike": 75.0, "dte_days": 29},
                            {"action": "BUY", "right": "P", "strike": 60.0, "dte_days": 29}],
                   "roll_meta": {"expiry": "2026-11-20", "dte": 29, "strike": 75.0, "credit_total": 40.0, "p_otm": None,
                                 "scores": {"structure": fit, "cushion": fit}, "structure": {}}}
            m["alternatives"].append(row)
            tr.rank_defenses(m)
            sc = {a["category"] if a["category"] in ("hold", "exit") else "fix": a["desk_score"] for a in m["alternatives"]
                  if a["category"] in ("hold", "exit") or a["name"] == row["name"]}
            if sc["fix"] > sc["hold"] > sc["exit"] and sc["fix"] - sc["exit"] < tr.NONVIABLE_MARGIN:
                found = True
                pick = next(a for a in m["alternatives"] if a.get("is_desk_pick"))
                assert pick["category"] == "hold", (sc, pick["name"])
                assert m["desk_recommendation"]["reasons"][0].startswith("Holding scores")
                assert "raises the worst case" in m["desk_recommendation"]["reasons"][0]
                break
        if found:
            break
    assert found, "no configuration reproduced fix > hold > close within the margin"


# ── end to end: the live-shaped AAOI trap on the pinned world ─────────────────────────────────────────────────────
def test_aaoi_trap_end_to_end(monkeypatch):
    import spread_world as W
    p1, final = W.run_flow(monkeypatch, spot=68.5, cur_dte=8, earn_days=14, posture="tested", p_touch=99.0, bid_ask=True)
    an = p1.get("anatomy")
    assert an and an["net"]["theta_day"] < 0 and an["spread"]["max_loss"] == -966
    ev = p1.get("event") or {}
    assert str(ev.get("source", "")).startswith("straddles") and ev.get("implied_move_pct")
    assert "both legs exercise" in p1["assignment"]["consequence"]
    # phase 2: the ladder exists and its rows are on the ranked menu, all paid for (no new money)
    lad = final.get("ladder") or {}
    assert lad.get("rungs")
    rows = [a for a in final["alternatives"] if (a.get("roll_meta") or {}).get("route")]
    assert any(a["roll_meta"]["route"] == "csp" for a in rows)
    assert all(float(a["net_cash"]) >= -1 for a in rows if a["roll_meta"]["route"] != "same")      # no new money …
    assert all(float(a["net_cash"]) >= -0.15 * 10 * 100 for a in rows if a["roll_meta"]["route"] == "same")   # … except a small same-strikes debit
    for a in rows:
        assert a["steps"]["reconciled"] and len(a["steps"]["close"]) == 2           # closes BOTH legs of what you hold
    # a cash-secured conversion is never the desk's own pick (it hands the tail to the stock)
    pick = next(a for a in final["alternatives"] if a.get("is_desk_pick"))
    assert (pick.get("roll_meta") or {}).get("route") != "csp"
    goals = [g["key"] for g in (final.get("playbook") or {}).get("objectives") or []]
    assert goals == ["min_risk", "recover", "assign"]
    pts = " ".join(final["timing"]["points"])
    assert "in the money" in pts and "breached this cycle" not in pts
    # the pick never falls back to Close when holding outscores it (a rejected fix used to hand the pick to Close)
    hold = next(a for a in final["alternatives"] if a["category"] == "hold")
    close = next(a for a in final["alternatives"] if a["category"] == "exit")
    if pick is close:
        assert close["desk_score"] >= hold["desk_score"]


