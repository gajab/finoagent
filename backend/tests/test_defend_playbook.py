# ── the two-date lattice, the market's law, the search ─────────────────────────────────────────────────────────────
def test_lattice_is_exact_on_a_spread_and_a_married_put():
    vol = lambda d: 1.0
    sp = [{"right": "P", "strike": 80, "sign": -1, "qty": 1, "dte": 8}, {"right": "P", "strike": 70, "sign": 1, "qty": 1, "dte": 8}]
    e = pb.lattice_eval(sp, 34.0, spot=68.5, r=R, vol_of=vol, benchmark=-700)
    assert e["worst"] == -966 and e["best"] == 34 and e["worst_side"] == "down" 
    # keep the Oct $80 short, protection moved to a Nov $75 put bought for $4 net: if assigned, the shares are kept and floored
    diag = [{"right": "P", "strike": 80, "sign": -1, "qty": 1, "dte": 8}, {"right": "P", "strike": 75, "sign": 1, "qty": 1, "dte": 29}]
    e2 = pb.lattice_eval(diag, 34.0 - 400.0, spot=68.5, r=R, vol_of=vol, benchmark=-700)
    assert e2["worst"] == round(34 - 400 - 500)                              # assigned at 80, floored at 75: −$5 a share more
    assert e2["best"] is None                                                # …and the kept shares have no cap on the upside
    naked_call = [{"right": "C", "strike": 80, "sign": -1, "qty": 1, "dte": 8}]
    assert pb.lattice_eval(naked_call, 100.0, spot=68.5, r=R, vol_of=vol)["worst"] is None   # unbounded is flagged, never a number


def test_market_law_reprices_its_own_chain():
    import numpy as np
    S, dte = 68.5, 29
    smile = lambda k: 1.0 - 0.6 * math.log(k / S) + 0.8 * math.log(k / S) ** 2                 # a steep, smooth put skew
    bk = book(S, dte, smile, strikes=range(50, 100, 5))                                         # … on a short chain
    q = pb.market_law(bk, S, dte, R, 1.0)
    z, w = np.polynomial.hermite_e.hermegauss(80)
    w = w / w.sum()
    ST = q(np.array([pb._ncdf(float(x)) for x in z]))
    disc = math.exp(-R * dte / 365)
    for K in (55.0, 60.0, 65.0, 70.0):                                       # out-of-the-money puts — the law's own inputs
        model = disc * float((w * np.maximum(0.0, K - ST)).sum())
        assert model == pytest.approx(bk[K]["P"]["mid"], rel=0.04, abs=0.04), K
    fwd = S * math.exp(R * dte / 365)
    assert float((w * ST).sum()) == pytest.approx(fwd, rel=0.005)            # a martingale: the law's mean is the forward


def test_the_search_never_adds_risk_and_always_prices_the_users_roll():
    S = 68.5
    near = book(S, 8, 1.0)
    later = [("2026-11-06", 15, book(S, 15, 1.25)), ("2026-11-20", 29, book(S, 29, 1.1)), ("2026-12-18", 57, book(S, 57, 1.0))]
    held = held_spread(near)
