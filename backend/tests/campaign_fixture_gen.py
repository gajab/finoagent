"""Regenerates frontend/tests/fixtures/aaoi-campaign.json from the REAL backend code.

Replays the AAOI campaign (trade 180) through close_position / roll_position / _to_out / get_campaign_ledger, so the
frontend render tests consume exactly what the API returns — never a hand-written payload.

    cd backend && venv/bin/python tests/campaign_fixture_gen.py      (from the main checkout's venv in a worktree)
"""
import asyncio
import json
import pathlib
import sys
from types import SimpleNamespace

sys.path.insert(0, str(pathlib.Path(__file__).parent))
sys.path.insert(0, str(pathlib.Path(__file__).parent.parent))
import test_campaign_math as T                      # noqa: E402  (reuses the replay helpers)
import app.routers.saved_strategy_router as R      # noqa: E402

OUT = pathlib.Path(__file__).parent.parent.parent / "frontend" / "tests" / "fixtures" / "aaoi-campaign.json"

if __name__ == "__main__":
    row = T._replay(entry=(0.59, 0.25, 2.34, 1.85), call_close=(0.12, 0.12), put70_close=3.80,
                    put80_buyback=12.10, new_put_premium=11.60)
    camp = asyncio.run(R.get_campaign_ledger(strategy_id=180, user=SimpleNamespace(id=1), db=T._DB(row)))
    out = {"_about": "Generated by backend/tests/campaign_fixture_gen.py — the real AAOI replay (trade 180) through the real handlers.",
           "trade": R._to_out(row).model_dump(), "campaign": camp}
    OUT.write_text(json.dumps(out, indent=1, default=str))
    print("wrote", OUT, "| events:", [e["title"] for e in camp["ledger"]["events"]])
